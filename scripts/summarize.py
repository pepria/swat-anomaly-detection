"""Collect all result tables into outputs/results_tables.md (used by RESULTS.md)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from swatad import config as C  # noqa: E402

O = C.OUT_DIR
out = ["# Result tables (generated by scripts/summarize.py)", ""]


def ms(x):
    return f"{x.mean():.3f} ± {x.std():.3f}" if len(x) > 1 else f"{x.mean():.3f}"


m = pd.read_csv(O / "metrics_all.csv")
for run in [r for r in ["a12_A11-A10_noAIT", "a12_A11-A10_all", "a12_A11_noAIT", "a12_A11_all",
                        "s2015_normal_noAIT", "s2015_normal_all"] if r in set(m.run)]:
    d = m[(m.run == run) & m.variant.isin(["model", "model+rules", "rules"])]
    g = d.groupby(["model", "variant"], sort=False).agg(
        AUC_ROC=("auc_roc", ms), AUC_PR=("auc_pr", "mean"), F1=("f1", "mean"),
        FPR_clean=("fpr_clean", "mean"), event_recall=("event_recall", "mean"),
        overlap_recall=("event_recall_overlap", "mean"), false_alarm_events=("false_alarm_events", "mean"),
        event_precision=("event_precision", "mean"), median_delay_s=("median_delay_s", "mean"),
        seeds=("seed", "nunique")).round(3).reset_index()
    out += [f"## {run}", "", g.to_markdown(index=False), ""]
    t = m[(m.run == run) & (m.variant == "model (train thr)")].groupby("model")["fpr_clean"].mean().round(3)
    if len(t):
        out += ["FPR on clean normal data with the *training* threshold (no re-calibration): "
                + ", ".join(f"{k} {v}" for k, v in t.items()), ""]

s = O / "synthetic" / "synthetic_summary.csv"
if s.exists():
    s = pd.read_csv(s)
    for var in ["model", "model+rules"]:
        pv = s[s.variant == var].pivot(index="type", columns="model", values="recall").round(2)
        out += [f"## Synthetic injection: event recall by type ({var})", "", pv.to_markdown(), ""]
    allr = s[s.type == "ALL"][["model", "variant", "n", "recall", "median_delay_s", "hit_at_1", "hit_at_3",
                               "false_alarm_events"]].round(3)
    out += ["## Synthetic injection: overall (recall, delay, root-cause localisation)", "",
            allr.to_markdown(index=False), ""]

for f in sorted((O / "explanations").glob("*_eval.csv")):
    e = pd.read_csv(f)
    out += [f"## Explanation quality: {f.stem.replace('_eval', '')}", "",
            e[["attack_id", "top3_contributors", "target_in_top3", "target_in_top3_or_rules",
               "predicted_category", "true_category", "known_attack_correct",
               "loo_top1_same_category"]].to_markdown(index=False), "",
            "Mean: " + ", ".join(f"{c} {e[c].mean():.2f}" for c in
                                 ["target_in_top3", "target_in_top3_or_rules", "category_correct",
                                  "known_attack_correct", "loo_top1_same_category"]), ""]

(O / "results_tables.md").write_text("\n".join(out))
print("\n".join(out))
